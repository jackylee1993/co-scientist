"""Assemble a human-readable report from the run's files.

The report is intentionally assembled from artefacts, not regenerated by an
LLM: every claim in it can be traced to a hypothesis card, a review, a match,
or a landscape note.  The final-synthesis prompt may add prose on top, but it
must not introduce new facts.
"""
from __future__ import annotations

from collections import Counter
from pathlib import Path

from .ratings import position_bias, rank_text, verbosity_bias
from .similarity import cluster_hypotheses, diversity_score, hypothesis_text, near_duplicates
from .util import as_text, mean, read_json, read_text, truncate


def _score(value) -> str:
    if isinstance(value, dict):
        value = value.get("score")
    if isinstance(value, (int, float)):
        return f"{value:.1f}"
    return "—"


def _evidence_line(e: dict) -> str:
    if not isinstance(e, dict):
        return f"- {as_text(e)}"
    source = e.get("source") or e.get("title") or e.get("doi") or e.get("url") or "未注明来源"
    tag = "已核验" if e.get("verified") else "待核验"
    supports = e.get("supports", "unknown")
    note = e.get("quote") or e.get("note") or ""
    return f"- [{tag}] {source}（{supports}）{('：' + truncate(note, 160)) if note else ''}"


def hypothesis_card(h: dict, reviews: list[dict] | None = None, rank: int | None = None) -> str:
    reviews = reviews or []
    lines = []
    head = f"### {h['id']} · {h.get('title', '')}"
    if rank:
        head = f"### #{rank} {h['id']} · {h.get('title', '')}"
    lines.append(head)
    lines.append("")
    lines.append(f"**一句话假设**：{h.get('claim', '')}")
    lines.append("")
    if h.get("mechanism"):
        lines.append("**机制链**：")
        for i, step in enumerate(h["mechanism"], 1):
            lines.append(f"{i}. {step}")
        lines.append("")
    if h.get("predictions"):
        lines.append("**可证伪预测**：")
        for p in h["predictions"]:
            if isinstance(p, dict):
                if p.get("if_true"):
                    lines.append(f"- 若成立：{p['if_true']}")
                if p.get("if_false"):
                    lines.append(f"- 若证伪：{p['if_false']}")
                if p.get("observation"):
                    lines.append(f"- 观测：{p['observation']}")
            else:
                lines.append(f"- {p}")
        lines.append("")
    test = h.get("testability") or {}
    if test:
        lines.append("**最小验证**：")
        if test.get("minimal_experiment"):
            lines.append(f"- 实验：{test['minimal_experiment']}")
        if test.get("data_needed"):
            lines.append(f"- 数据/样品：{test['data_needed']}")
        if test.get("controls"):
            lines.append(f"- 对照：{test['controls']}")
        if test.get("endpoint"):
            lines.append(f"- 指标/终点：{test['endpoint']}")
        if test.get("time"):
            lines.append(f"- 周期：{test['time']}")
        if test.get("statistics"):
            lines.append(f"- 统计：{test['statistics']}")
        if test.get("failure_modes"):
            lines.append("- 失败模式：" + "；".join(map(str, test["failure_modes"])))
        lines.append("")
    nov = h.get("novelty") or {}
    if nov:
        lines.append(f"**新颖性**：{_score(nov)}/10"
                     + (f"；最近工作：{nov.get('closest_prior_work')}" if nov.get("closest_prior_work") else ""))
        if nov.get("delta"):
            lines.append(f"- 增量：{nov['delta']}")
        lines.append("")
    scores = {
        "novelty": _score(h.get("novelty")),
        "testability": _score(h.get("testability")),
        "impact": _score(h.get("impact")),
        "feasibility": _score(h.get("feasibility")),
        "self-confidence": f"{h.get('confidence'):.2f}" if isinstance(h.get("confidence"), (int, float)) else "—",
    }
    lines.append("**自评**：" + "｜".join(f"{k} {v}" for k, v in scores.items()))
    lines.append("")
    if h.get("assumptions"):
        lines.append("**承重假设**：")
        for a in h["assumptions"]:
            if isinstance(a, dict):
                flag = "承重" if a.get("load_bearing", True) else "非承重"
                lines.append(f"- [{flag}/{a.get('status', 'untested')}] {a.get('text', '')}")
            else:
                lines.append(f"- {a}")
        lines.append("")
    if h.get("evidence"):
        lines.append("**证据**：")
        lines.extend(_evidence_line(e) for e in h["evidence"])
        lines.append("")
    if h.get("risks"):
        lines.append("**风险 / 最可能被攻击的点**：")
        lines.extend(f"- {r}" for r in h["risks"])
        lines.append("")
    if reviews:
        lines.append("**评审摘要**：")
        for r in reviews[-4:]:
            verdict = r.get("verdict", "?")
            rtype = r.get("review_type", "?")
            fatal = "；".join(map(str, r.get("fatal_flaws", []) or []))
            lines.append(f"- {rtype}/{verdict}（conf={r.get('confidence', '?')}）"
                         + (f"：{truncate(fatal, 200)}" if fatal else ""))
        lines.append("")
    lines.append(f"*状态：{h.get('status', 'active')}｜来源策略：{(h.get('provenance') or {}).get('strategy', '?')}"
                 f"｜簇：{h.get('cluster', '?')}*")
    lines.append("")
    return "\n".join(lines)


def _section(title: str, body: str, fallback: str = "未生成。") -> list[str]:
    return [f"## {title}", "", body.strip() if body and body.strip() else fallback, ""]


def _render_retrospective(data: dict) -> str:
    """Turn retrospective.json into a readable report section."""
    lines: list[str] = []
    for title, key, field in (
        ("做得好的", "what_worked", "strategy"),
        ("没做好的", "what_failed", "strategy"),
        ("反复出现的批评", "recurring_critiques", "pattern"),
    ):
        items = data.get(key) or []
        if items:
            lines.append(f"**{title}**：")
            for item in items:
                if isinstance(item, dict):
                    label = item.get(field) or item.get("text") or ""
                    evidence = item.get("evidence") or item.get("suggested_fix") or ""
                    lines.append(f"- {label}" + (f"：{evidence}" if evidence else ""))
                else:
                    lines.append(f"- {item}")
            lines.append("")
    lessons = data.get("lessons") or []
    if lessons:
        lines.append("**可迁移经验（lessons）**：")
        for item in lessons:
            if isinstance(item, dict):
                text = item.get("text") or item.get("lesson") or ""
                scope = item.get("scope", "run")
                conf = item.get("confidence", "?")
                lines.append(f"- [{scope}, conf={conf}] {text}")
            else:
                lines.append(f"- {item}")
        lines.append("")
    edits = data.get("proposed_edits") or []
    if edits:
        lines.append("**建议的 playbook 修改（需人工批准）**：")
        for item in edits:
            if isinstance(item, dict):
                lines.append(
                    f"- {item.get('target', '?')}：{item.get('change', '')}"
                    + (f"（证据：{item.get('evidence')}）" if item.get("evidence") else "")
                )
            else:
                lines.append(f"- {item}")
        lines.append("")
    risks = data.get("overfitting_risks") or []
    if risks:
        lines.append("**过拟合/反馈回路风险**：")
        lines.extend(f"- {r}" for r in risks)
        lines.append("")
    return "\n".join(lines).strip()


def build_report(run, top: int = 5) -> str:
    data = run.load()
    goal = run.load_goal()
    rows = run.leaderboard()
    hypotheses = {h["id"]: h for h in run.hypotheses()}
    reviews = run.reviews()
    reviews_by_h: dict[str, list[dict]] = {}
    for r in reviews:
        reviews_by_h.setdefault(r.get("hypothesis_id"), []).append(r)
    matches = run.matches()
    active_hs = [h for h in hypotheses.values() if h.get("status") != "rejected"]
    clusters = cluster_hypotheses(active_hs)
    div = diversity_score(active_hs)
    warnings = [w for w in run.warnings() if "report.md not generated" not in w]

    lines: list[str] = []
    title = goal.get("title") or "Co-Scientist 研究报告"
    lines += [f"# {title}", ""]
    lines += [
        f"> 运行 ID：`{data.get('run_id')}`｜配置：`{data.get('profile')}`｜"
        f"生成时间：{data.get('updated_at', '')}｜"
        f"假设 {len(hypotheses)} 个｜评审 {len(reviews)} 次｜比较 {len(matches)} 场",
        "",
    ]

    # Executive summary
    lines += ["## 0. 执行摘要", ""]
    if rows:
        top_rows = rows[:min(3, len(rows))]
        lines.append("当前锦标赛前三名：" if matches else
                     "当前候选前三名（尚无比赛，Elo 仅为初始值）：")
        lines.append("")
        for i, r in enumerate(top_rows, 1):
            ci = (f"95% CI {r['elo_ci_low']}–{r['elo_ci_high']}"
                  if r.get("elo_ci_low") is not None else "尚无比赛，CI 不可估")
            lines.append(f"{i}. **{r['id']} {r['title']}** — Elo {r['elo']} "
                         f"（{ci}，{r['matches']} 场）")
        lines.append("")
        lines.append("**建议**：先看第 1 名的承重假设和最小验证；若 2 周 pilot 不能区分"
                     "“假设成立/实验失败/替代解释”，则降低优先级。")
    else:
        lines.append("尚未产生可排序的假设。")
    lines.append("")
    lines.append(f"多样性：{div['clusters']} 个簇，最大簇 {div['largest_cluster']} 个假设，"
                 f"冗余度 {div['redundancy']:.0%}。"
                 + (" **警告：假设过度集中，建议增加 out-of-box 探索。**" if div["n"] and div["redundancy"] > 0.6 else ""))
    lines.append("")
    if warnings:
        lines.append(f"未闭合项：{len(warnings)} 条（详见第 9 节）。")
        lines.append("")

    # Goal
    lines += ["## 1. 研究目标与约束", ""]
    lines.append(f"**问题**：{goal.get('question') or goal.get('raw') or '—'}")
    lines.append("")
    if goal.get("background"):
        lines.append(f"**背景**：{goal['background']}")
        lines.append("")
    for key, label in (("known", "已知"), ("unknown", "未知"), ("non_goals", "明确不做")):
        vals = goal.get(key) or []
        if vals:
            lines.append(f"**{label}**：")
            lines.extend(f"- {v}" for v in vals)
            lines.append("")
    constraints = goal.get("constraints") or {}
    if constraints:
        lines.append("**约束**：")
        for k, v in constraints.items():
            lines.append(f"- {k}: {v}")
        lines.append("")
    criteria = goal.get("evaluation_criteria") or []
    if criteria:
        lines.append("**评审标准**：")
        for c in criteria:
            if isinstance(c, dict):
                lines.append(f"- {c.get('name', '?')}（权重 {c.get('weight', '?')}）：{c.get('rubric', '')}")
            else:
                lines.append(f"- {c}")
        lines.append("")
    if goal.get("assumptions"):
        lines.append("**运行假设**（信息不足时的显式假设）：")
        lines.extend(f"- {a}" for a in goal["assumptions"])
        lines.append("")
    if goal.get("clarifying_questions"):
        lines.append("**待 PI 确认的问题**：")
        lines.extend(f"- {q}" for q in goal["clarifying_questions"])
        lines.append("")

    # Landscape
    landscape = read_text(run.root / "landscape.md")
    lines += _section("2. 证据地形（Landscape）", landscape,
                      "未生成。运行 `landscape` 阶段后再生成报告。")

    # Leaderboard
    lines += ["## 3. 锦标赛排行榜", "", "```text", rank_text(rows), "```", ""]
    if matches:
        pb = position_bias(matches)
        if pb["n"]:
            coverage = pb.get("coverage", 1.0)
            lines.append(f"- 位置偏差检查：先展示者胜率 {pb['first_win_rate']:.1%}（n={pb['n']}，"
                         f"p={pb['p']:.3f}）。" + (" **显著，需交换顺序复赛。**" if pb["p"] < 0.05 else " 未发现显著偏差。")
                         + ("" if coverage >= 0.8 else
                            f" 注意：只有 {coverage:.0%} 的比赛记录了出场顺序，结论不可靠。"))
        vb = verbosity_bias(matches, {hid: hypothesis_text(h) for hid, h in hypotheses.items()})
        if vb.get("n"):
            lines.append(f"- 篇幅偏差检查：胜者平均 {vb['mean_winner_chars']:.0f} 字符，"
                         f"败者 {vb['mean_loser_chars']:.0f}，比值 {vb['ratio']:.2f}。"
                         + (" **胜者明显更长，需检查是否奖励了啰嗦。**" if vb.get("flag") else ""))
    lines.append("")

    # Top hypotheses
    lines += [f"## 4. 前 {top} 名假设卡", ""]
    for row in rows[:top]:
        h = hypotheses.get(row["id"])
        if h:
            lines.append(hypothesis_card(h, reviews_by_h.get(row["id"]), rank=row["rank"]))
    if not rows:
        lines.append("尚无假设。")

    # Diversity
    lines += ["## 5. 假设空间与多样性", ""]
    if clusters:
        lines.append("| 簇 | 大小 | 成员 | 关键词 |")
        lines.append("|---|---:|---|---|")
        for c in clusters:
            lines.append(f"| {c['cluster']} | {c['size']} | {', '.join(c['members'])} | {', '.join(c['keywords'][:6])} |")
        lines.append("")
    dups = near_duplicates(list(hypotheses.values()))
    if dups:
        lines.append("**近重复对（建议合并或明确差异）**：")
        for p in dups[:10]:
            lines.append(f"- {p['a']} ~ {p['b']}（相似度 {p['similarity']}）")
        lines.append("")
    rejected = [h for h in hypotheses.values() if h.get("status") == "rejected"]
    if rejected:
        lines.append(f"**已淘汰（{len(rejected)} 个，保留记录但不参与排序）**：")
        for h in rejected:
            fatal = ""
            hrs = reviews_by_h.get(h["id"], [])
            if hrs:
                fatal = "；".join(map(str, hrs[-1].get("fatal_flaws", []) or []))
            lines.append(f"- {h['id']} {h.get('title', '')}" + (f"：{truncate(fatal, 160)}" if fatal else ""))
        lines.append("")

    # Meta-review
    meta = read_text(run.meta_dir / "meta_review.md")
    lines += _section("6. 元评审与研究总览（Meta-review）", meta,
                      "未生成。运行 `meta-review` 阶段后再生成。")

    # Experiment plan
    plan = read_text(run.meta_dir / "experiment_plan.md")
    lines += _section("7. 推荐实验方案", plan,
                      "未生成。可用 `final-synthesis` 提示词从 top 假设生成。")

    # RSI
    retro_file = run.meta_dir / "retrospective.json"
    if retro_file.exists():
        try:
            retro = _render_retrospective(read_json(retro_file))
        except Exception:
            retro = read_text(run.meta_dir / "retrospective.md")
    else:
        retro = read_text(run.meta_dir / "retrospective.md")
    lines += _section("8. RSI 复盘：这次运行学到了什么", retro,
                      "未生成。运行结束后执行 `rsi retrospective`。")

    # Integrity
    lines += ["## 9. 完整性、局限与未闭合项", ""]
    lines.append("**证据核验**：")
    verified = sum(1 for h in hypotheses.values() for e in (h.get("evidence") or [])
                   if isinstance(e, dict) and e.get("verified"))
    total_e = sum(1 for h in hypotheses.values() for e in (h.get("evidence") or []))
    lines.append(f"- 证据条目 {total_e} 条，已核验 {verified} 条，待核验 {total_e - verified} 条。"
                 "所有“待核验”引文在正式使用前必须回原文核对。")
    lines.append("- 本报告是**假设生成与排序**，不是事实陈述；Elo 是相对评分，不是客观真值。")
    lines.append("- 评审由 AI 完成，可能存在位置偏差、篇幅偏差、共识幻觉；关键结论需领域专家复核。")
    if warnings:
        lines.append("")
        lines.append("**未闭合项**：")
        lines.extend(f"- {w}" for w in warnings[:30])
        if len(warnings) > 30:
            lines.append(f"- ……另有 {len(warnings) - 30} 条，见 `cosci validate`。")
    lines.append("")

    # Appendix
    lines += ["## 10. 附录：运行统计", ""]
    lines.append(f"- phase: `{data.get('phase')}` / status: `{data.get('status')}`")
    lines.append(f"- counters: `{data.get('counters')}`")
    lines.append(f"- 评审类型分布：{dict(Counter(r.get('review_type', '?') for r in reviews))}")
    if matches:
        lines.append(f"- 平均判官置信度：{mean([m.get('confidence', 0) for m in matches if isinstance(m.get('confidence'), (int, float))]):.2f}")
    lines.append("- 文件：`goal.json`、`landscape.md`、`hypotheses/`、`reviews/`、"
                 "`tournament.json`、`meta/`、`prompts/`、`run.log`")
    lines.append("")
    return "\n".join(lines)
